import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { transform } from 'esbuild';

const root = 'sites/evidence-bouncer-public';
await mkdir(`${root}/assets`, { recursive: true });
await mkdir(`${root}/data`, { recursive: true });
for (const name of ['index.html', 'app.js', 'style.css']) await copyFile(`bouncer/web/${name}`, `${root}/assets/${name}`);
let html = await readFile(`${root}/assets/index.html`, 'utf8');
html = html.replace('LOCAL WORKSPACE', 'PUBLIC DEMO').replace('Results are saved locally.', 'Your results are saved in this browser session.').replace('Download run JSON ↓', 'Download run JSON ↓');
await writeFile(`${root}/assets/index.html`, html);
let app = await readFile(`${root}/assets/app.js`, 'utf8');
const start = app.indexOf('    const { id } = await api(\'/api/runs\'');
const end = app.indexOf("    if (job.run) render(job.run); else throw new Error(job.error || 'Run failed.');", start);
if (start < 0 || end < 0) throw new Error('Could not locate local job transport.');
const last = end + "    if (job.run) render(job.run); else throw new Error(job.error || 'Run failed.');".length;
app = app.slice(0, start) + `    $('progress').textContent = 'Extracting claims → checking evidence → selecting grounded rewrite…';
    const { run } = await api('/api/check', { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-Bouncer-Local': '1' }, body: JSON.stringify({ draft }) });
    sessionStorage.setItem('evidence-bouncer-run', JSON.stringify(run));
    $('progress').textContent = 'Complete · result saved in this browser session. Download JSON to keep it.';
    render(run);` + app.slice(last);
app = app.replace("if (run) { $('draft').value = run.original_draft; updateDraft(); render(run, true); }", "const saved = sessionStorage.getItem('evidence-bouncer-run'); const selected = saved ? JSON.parse(saved) : run; if (selected) { $('draft').value = selected.original_draft; updateDraft(); render(selected, true); if (saved) { lastRunLabel = 'SAVED BROWSER RUN'; $('run-kind').textContent = lastRunLabel; } }");
await writeFile(`${root}/assets/app.js`, app);
const config = JSON.parse(await readFile('packs/tonight/pack.json', 'utf8'));
const pack = { id: config.id, model: config.model, draft: await readFile(`packs/tonight/${config.draft}`, 'utf8'), sources: [], prompts: {} };
for (const source of config.sources) { const content = await readFile(`packs/tonight/${source.file}`, 'utf8'); pack.sources.push({ ...source, content, sha256: createHash('sha256').update(content).digest('hex') }); }
for (const [key, path] of Object.entries(config.prompts)) pack.prompts[key] = await readFile(`packs/tonight/${path}`, 'utf8');
await writeFile(`${root}/data/pack.json`, JSON.stringify(pack, null, 2));
const recorded = JSON.parse(await readFile('results/bouncer/2026-11-17T10-45-31-267Z-572f1e43/run.json', 'utf8'));
delete recorded.pack_folder;
await writeFile(`${root}/data/recorded-run.json`, JSON.stringify(recorded, null, 2));
let core = '';
for (const [file, from, to] of [
  ['generator.ts', 'export function validateClaims', 'export async function generateClaims'],
  ['checker.ts', 'export function validateVerdicts', 'export async function checkClaims'],
  ['loop.ts', 'export function groundedRewrite', 'export async function runBouncerLoop'],
  ['report.ts', 'export function scoreboard', null],
]) {
  const source = await readFile(`bouncer/${file}`, 'utf8');
  core += source.slice(source.indexOf(from), to ? source.indexOf(to) : undefined) + '\n';
}
const js = await transform(core, { loader: 'ts', target: 'es2022' });
await writeFile(`${root}/core.js`, '// Portable snapshot of the CLI validation and report functions. Generated by scripts/prepare-site.mjs.\n' + js.code);
console.log('Prepared sanitized public assets, pack, recorded run, and shared validation snapshot. No environment files copied.');
